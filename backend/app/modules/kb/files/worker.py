"""Trusted isolated bootstrap, invoked by absolute path with Python -I.

No document-supplied code, commands, paths or environment. Linux x86_64/aarch64,
libseccomp is required; unsupported hosts fail closed.
"""

import codecs
import ctypes
import errno
import hashlib
import io
import json
import os
import resource
import socket
import sys
import time
import warnings
from collections.abc import Callable
from pathlib import Path

import pypdf
from pypdf import _cmap, _text_extraction  # noqa: F401  (preload before seccomp)


def image_task(source: int, *, check: bool) -> None:
    """Only called after the default-deny filter, on a sealed input fd."""
    from PIL import Image, ImageOps

    maximum = 5 * 1024**2
    Image.MAX_IMAGE_PIXELS = 16_000_000
    warnings.simplefilter("error")
    data = os.read(source, maximum + 1)
    if not 0 < len(data) <= maximum:
        raise ValueError("image size")
    with Image.open(io.BytesIO(data), formats=("JPEG", "PNG")) as image:
        fmt = image.format
        if (
            image.width > 4096
            or image.height > 4096
            or image.width * image.height > 16_000_000
            or getattr(image, "n_frames", 1) != 1
            or getattr(image, "is_animated", False)
        ):
            raise ValueError("image bounds")
        image.verify()
    # verify() checks container integrity; load() forces complete pixel decoding.
    with Image.open(io.BytesIO(data), formats=("JPEG", "PNG")) as image:
        image.load()
        if check:
            return
        ImageOps.exif_transpose(image, in_place=True)
        # Preserve alpha (including palette transparency) for PNG; JPEG stays
        # JPEG and is explicitly RGB. No cross-format alpha loss/compositing.
        mode = "RGBA" if fmt == "PNG" else "RGB"
        converted = image.convert(mode)
        clean = Image.new(mode, converted.size)
        clean.paste(converted)
        converted.close()
    buffer = io.BytesIO()
    clean.save(buffer, format=fmt)
    clean.close()
    result = buffer.getvalue()
    if not 0 < len(result) <= maximum:
        raise ValueError("image output size")
    # Independently decode the newly encoded container before returning it.
    with Image.open(io.BytesIO(result), formats=("JPEG", "PNG")) as final:
        final.load()
        if final.format != fmt:
            raise ValueError("image format")
        # JPEG's standard JFIF structures are harmless, generated by Pillow.
        allowed = (
            {
                "jfif",
                "jfif_version",
                "jfif_unit",
                "jfif_density",
            }
            if fmt == "JPEG"
            else set()
        )
        if set(final.info) - allowed:
            raise ValueError("image metadata")
    sys.stdout.buffer.write(result)


def restrictions(cpu: int, memory: int, *, tool: bool = False) -> None:
    if os.geteuid() == 0:
        raise RuntimeError("nonroot required")
    resource.setrlimit(resource.RLIMIT_CPU, (cpu, cpu))
    resource.setrlimit(resource.RLIMIT_AS, (memory, memory))
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    size_limit = 128 * 1024**2 if tool else 0
    resource.setrlimit(resource.RLIMIT_FSIZE, (size_limit, size_limit))
    resource.setrlimit(resource.RLIMIT_NOFILE, (64, 64))
    libc = ctypes.CDLL(None, use_errno=True)
    if libc.prctl(38, 1, 0, 0, 0):  # PR_SET_NO_NEW_PRIVS
        raise RuntimeError("no_new_privs")


def network_filter(*, parser: bool) -> None:
    lib = ctypes.CDLL("libseccomp.so.2", use_errno=True)
    lib.seccomp_init.argtypes = [ctypes.c_uint32]
    lib.seccomp_init.restype = ctypes.c_void_p
    lib.seccomp_syscall_resolve_name.argtypes = [ctypes.c_char_p]
    lib.seccomp_rule_add.argtypes = [
        ctypes.c_void_p,
        ctypes.c_uint32,
        ctypes.c_int,
        ctypes.c_uint,
    ]
    lib.seccomp_load.argtypes = [ctypes.c_void_p]
    lib.seccomp_release.argtypes = [ctypes.c_void_p]
    context = lib.seccomp_init(0x00050000 | errno.EPERM if parser else 0x7FFF0000)
    if not context:
        raise RuntimeError("seccomp")
    blocked = [
        "socket",
        "socketpair",
        "connect",
        "bind",
        "listen",
        "accept",
        "accept4",
        "sendto",
        "sendmsg",
        "sendmmsg",
        "recvfrom",
        "recvmsg",
        "recvmmsg",
        "setsid",
        "setpgid",
        "ptrace",
        "process_vm_readv",
        "process_vm_writev",
        "pidfd_getfd",
        "mount",
        "unshare",
        "setns",
        "bpf",
        "io_uring_setup",
        "open_by_handle_at",
        "userfaultfd",
    ]
    allowed = [
        "read",
        "write",
        "readv",
        "writev",
        "pread64",
        "close",
        "lseek",
        "fstat",
        "dup",
        "dup2",
        "dup3",
        "fcntl",
        "brk",
        "mmap",
        "mremap",
        "munmap",
        "mprotect",
        "madvise",
        "futex",
        "rt_sigaction",
        "rt_sigprocmask",
        "rt_sigreturn",
        "sigaltstack",
        "clock_gettime",
        "clock_nanosleep",
        "nanosleep",
        "getrandom",
        "getpid",
        "gettid",
        "getuid",
        "geteuid",
        "getgid",
        "getegid",
        "getrusage",
        "sched_yield",
        "restart_syscall",
        "exit",
        "exit_group",
    ]
    # Parser: default deny, including every pathname, network, exec and process
    # creation syscall. Only already-loaded code and inherited sealed input fd.
    names = allowed if parser else blocked
    action = 0x7FFF0000 if parser else 0x00050000 | errno.EPERM
    try:
        for name in names:
            number = lib.seccomp_syscall_resolve_name(name.encode())
            if number >= 0 and lib.seccomp_rule_add(context, action, number, 0):
                raise RuntimeError("seccomp rule")
        if lib.seccomp_load(context):
            raise RuntimeError("seccomp load")
    finally:
        lib.seccomp_release(context)


def main() -> None:
    task, descriptor, cpu, memory = sys.argv[1:5]
    if task in {"image", "image-check"}:
        # EXIF uses Pillow's TIFF metadata reader even for JPEG. Preload it
        # before seccomp; Image.open still allowlists JPEG/PNG exclusively.
        # Never call Image.init(): unrelated format plugins are unnecessary.
        from PIL import (  # noqa: F401
            Image,
            ImageOps,
            JpegImagePlugin,
            PngImagePlugin,
            TiffImagePlugin,  # noqa: F401
        )

        codecs.lookup("latin-1")
        codecs.lookup("utf-8")
        codecs.lookup("utf-16-be")
    restrictions(int(cpu), int(memory), tool=task == "exec")
    if task == "exec":
        network_filter(parser=False)
        os.execv(sys.argv[5], sys.argv[5:])
    observed = {
        "uid": os.geteuid(),
        "cpu": resource.getrlimit(resource.RLIMIT_CPU)[0],
        "memory": resource.getrlimit(resource.RLIMIT_AS)[0],
        "environment": sorted(os.environ),
    }
    # Codec modules are trusted code and must be loaded before pathname opens
    # become forbidden. Unsupported PDF encodings still fail closed.
    for encoding in ("charmap", "utf-16-be", "utf-16-le", "latin-1", "cp1252"):
        codecs.lookup(encoding)
    network_filter(parser=True)
    source = int(descriptor)
    if task in {"image", "image-check"}:
        image_task(source, check=task == "image-check")
    elif task in {"pdf", "pdf-info", "pdf-text"}:
        with os.fdopen(os.dup(source), "rb") as file:
            reader = pypdf.PdfReader(file, strict=True)
            if reader.is_encrypted or len(reader.pages) < 1:
                raise ValueError("pdf")
            # Touch page dictionaries; no text extraction or actions are executed.
            for page in reader.pages:
                if page.get("/Type") != "/Page" or "/MediaBox" not in page:
                    raise ValueError("pdf")
            if task != "pdf":
                if len(reader.pages) > 100:
                    raise ValueError("pdf page limit")
                result: dict[str, object] = {"page_count": len(reader.pages)}
                if task == "pdf-text":
                    pages = []
                    total = 0
                    for page in reader.pages:
                        value = page.extract_text() or ""
                        total += len(value.encode("utf-8"))
                        if total > 12000:
                            raise ValueError("pdf text limit")
                        pages.append(value)
                    result["pages"] = pages
                print(json.dumps(result, ensure_ascii=True))
    elif task == "inspect":
        data = os.read(source, 26214401)
        print(
            json.dumps({"size": len(data), "sha256": hashlib.sha256(data).hexdigest()})
        )
    elif task == "probe":
        operations: dict[str, Callable[[], object]] = {
            "filesystem": lambda: os.open("/etc/passwd", os.O_RDONLY),
            "network": socket.socket,
            "fork": os.fork,
            "input_write": lambda: os.write(source, b"changed"),
        }
        for name, operation in operations.items():
            try:
                operation()
                observed[name] = 0
            except OSError as error:
                observed[name] = error.errno
        print(json.dumps(observed))
    elif task == "network":
        socket.socket()
    elif task == "filesystem":
        Path("/run/secrets/runtime_password").read_bytes()
    elif task == "write":
        os.write(source, b"changed")
    elif task == "fork":
        os.fork()
    elif task == "cpu":
        while True:
            pass
    elif task == "memory":
        io.BytesIO(b"x" * (int(memory) * 2))
    elif task == "timeout":
        time.sleep(60)
    elif task == "output":
        while True:
            print("x" * 4096, flush=True)
    else:
        raise ValueError("task")


if __name__ == "__main__":
    try:
        main()
    except BaseException:
        # Library warnings are bounded by the parent; never forwarded to logs.
        sys.exit(70)
