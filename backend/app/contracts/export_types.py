PREAMBLE = """// Generated by app.contracts.export_types; do not edit by hand.
// Numeric/string length bounds and cross-field rules are enforced by the backend.
export type UUID = `${string}-${string}-${string}-${string}-${string}`
export type DecimalString = `${bigint}` | `${bigint}.${string}`
declare const secretTokenBrand: unique symbol
export type SecretToken = string & { readonly [secretTokenBrand]: true }
export type ImageURL = `/api/v1/catalog/items/${UUID}/image/${string}`
export type DocumentURL = `/api/v1/documents/${UUID}/versions/${UUID}/file`
export type UTCDateTime = `${string}Z` | `${string}+00:00`
export type JsonValue = null | boolean | number | string | JsonValue[]
  | { [key: string]: JsonValue }

/** Encode 32 cryptographically random bytes elsewhere; never place tokens in URLs. */
export function secretToken(value: string): SecretToken {
  if (!/^[0-9a-f]{64}$/.test(value)) throw new Error("Invalid token encoding")
  return value as SecretToken
}
"""


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return "(" + " | ".join(ts_type(part) for part in schema[union]) + ")"
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema.get("type")
    if kind == "string":
        if schema.get("format") == "uuid":
            return "UUID"
        if schema.get("format") == "date-time":
            return "UTCDateTime"
        pattern = schema.get("pattern", "")
        if pattern == MONEY_PATTERN:
            return "DecimalString"
        if pattern == r"^[0-9a-f]{64}$" and schema.get("title") in (
            "Session Token",
            "X-Request-Token",
            "X-Chat-Token",
        ):
            return "SecretToken"
        if pattern.startswith("^/api/v1/catalog/items/"):
            return "ImageURL"
        if pattern.startswith("^/api/v1/documents/"):
            return "DocumentURL"
        return "string"
    if kind in ("number", "integer"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if schema.get("maxItems") == 0:
            return "[]"
        return "Array<" + ts_type(schema["items"]) + ">"
    if kind == "object":
        if "properties" not in schema:
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                return "{ [key: string]: " + ts_type(extra) + " }"
            raise ValueError(f"untyped object in schema: {schema}")
        required = schema.get("required", [])
        fields = [
            f"  {json.dumps(name)}{'?' if name not in required else ''}: "
            f"{ts_type(prop)}"
            for name, prop in schema["properties"].items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    raise ValueError(f"unsupported schema: {schema}")


def render_types() -> str:
    _, schema = models_json_schema([(model, "validation") for model in MODELS])
    definitions = schema["$defs"]
    result = [PREAMBLE]
    for name, definition in sorted(definitions.items()):
        if name == "JsonValue":
            continue
        if name == "OrderCreate":
            # Mirror order_shape's discriminator rules, absent from field-only schema.
            result.append(f"type OrderCreateFields = {ts_type(definition)}\n")
            result.append("""export type OrderCreate = Omit<OrderCreateFields,
  "kind" | "items" | "comment" | "source" | "chat_session_id"> & (
    { kind: "commercial"; items: [OrderItemInput, ...OrderItemInput[]];
      comment?: string | null }
    | { kind: "support"; items: []; comment: string }
  ) & (
    { source: "site"; chat_session_id?: never }
    | { source: "chat"; chat_session_id: UUID }
  )
""")
        else:
            result.append(f"export type {name} = {ts_type(definition)}\n")
    result.append("""/** Header requirements depend on the source of the order. */
export type OrderSubmission =
  | { body: OrderCreate & { source: "site" }; headers: OrderHeaders }
  | { body: OrderCreate & { source: "chat" }; headers: OrderHeaders & ChatHeaders }
""")
    return "\n".join(result)


def render_fixtures() -> str:
    data = json.loads((API_DIR / "fixtures.json").read_text())
    if set(data) != set(FIXTURES):
        raise ValueError("fixture names and model registry differ")
    names = sorted({model.__name__ for model, _ in FIXTURES.values()})
    result = [
        "// Generated from fixtures.json; synthetic examples only.",
        "import type { " + ", ".join(names) + ' } from "./types"',
        "",
        "export const fixtures = " + json.dumps(data, ensure_ascii=False, indent=2),
        "satisfies {",
    ]
    for name, (model, many) in FIXTURES.items():
        suffix = "[]" if many else ""
        result.append(f"  {name}: {model.__name__}{suffix}")
    result.append("}\n")
    # A line break before `satisfies` triggers ASI in TypeScript.
    return "\n".join(result).replace("\n}\nsatisfies {", "\n} satisfies {")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in (
        ("types.ts", render_types()),
        ("fixtures.ts", render_fixtures()),
    ):
        path = API_DIR / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"stale generated contract: {path}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
